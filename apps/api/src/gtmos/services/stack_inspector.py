"""GTM Stack Inspector: a health report on the go-to-market system itself.

Each section computes its status from live queries and cites the numbers it used. Recommendations are
generated by rules over those numbers, ranked by the number of high-value accounts they affect, and each
carries its evidence. If a number isn't in `evidence`, it isn't in the report.

`causal_chains` goes one step further than a list of findings: it traces one set of accounts from a root
cause, through the mechanism that propagates it, to the business consequence, intersecting the same ids at
every link. Two findings that sound related ("36 accounts missing employee count", "90 unmatched routing
decisions") are usually not the same accounts, and the honest number is the intersection.
"""

